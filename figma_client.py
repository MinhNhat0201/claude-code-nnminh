"""
Figma REST API client.

Handles two modes of frame creation:
  1. REST API  — reading file info, listing pages/nodes, posting comments.
  2. Plugin code generation — produces JavaScript snippets that the user pastes
     into Figma's Plugin Runner (Plugins → Development → Open console) to
     actually draw frames on the canvas, since Figma's public REST API is
     read-only for node creation.
"""

from __future__ import annotations

import json
import os
from typing import Any

import httpx


FIGMA_API_BASE = "https://api.figma.com/v1"


class FigmaClient:
    def __init__(self, access_token: str | None = None, file_key: str | None = None):
        self.access_token = access_token or os.getenv("FIGMA_ACCESS_TOKEN", "")
        self.file_key = file_key or os.getenv("FIGMA_FILE_KEY", "")
        self._headers = {"X-Figma-Token": self.access_token}

    # ------------------------------------------------------------------
    # REST helpers
    # ------------------------------------------------------------------

    def _get(self, path: str, **params: Any) -> dict:
        url = f"{FIGMA_API_BASE}{path}"
        with httpx.Client() as client:
            resp = client.get(url, headers=self._headers, params=params, timeout=30)
            resp.raise_for_status()
            return resp.json()

    def _post(self, path: str, body: dict) -> dict:
        url = f"{FIGMA_API_BASE}{path}"
        with httpx.Client() as client:
            resp = client.post(
                url, headers=self._headers, json=body, timeout=30
            )
            resp.raise_for_status()
            return resp.json()

    # ------------------------------------------------------------------
    # File / page info (read-only — always available via REST)
    # ------------------------------------------------------------------

    def get_file_info(self) -> dict:
        """Return file name, pages, and top-level frame names."""
        if not self.file_key:
            return {"error": "FIGMA_FILE_KEY not set"}
        data = self._get(f"/files/{self.file_key}")
        doc = data.get("document", {})
        pages = [
            {
                "id": ch["id"],
                "name": ch["name"],
                "frames": [
                    {"id": f["id"], "name": f["name"]}
                    for f in ch.get("children", [])
                    if f.get("type") == "FRAME"
                ],
            }
            for ch in doc.get("children", [])
        ]
        return {
            "name": data.get("name"),
            "last_modified": data.get("lastModified"),
            "pages": pages,
        }

    def get_node(self, node_id: str) -> dict:
        """Fetch a single node by ID."""
        if not self.file_key:
            return {"error": "FIGMA_FILE_KEY not set"}
        data = self._get(f"/files/{self.file_key}/nodes", ids=node_id)
        return data.get("nodes", {}).get(node_id, {})

    def post_comment(self, message: str, x: float = 0, y: float = 0) -> dict:
        """Post a design annotation comment on the file canvas."""
        if not self.file_key:
            return {"error": "FIGMA_FILE_KEY not set"}
        return self._post(
            f"/files/{self.file_key}/comments",
            {"message": message, "client_meta": {"x": x, "y": y}},
        )

    # ------------------------------------------------------------------
    # Plugin code generation
    # ------------------------------------------------------------------
    # Figma's public REST API cannot create/modify nodes.  Instead we
    # generate JavaScript that uses the Figma Plugin API internally.
    # The user pastes this into Figma → Plugins → Development → Open console.

    @staticmethod
    def generate_frame_plugin_code(frames: list[dict]) -> str:
        """
        Generate Figma plugin JavaScript to create frames on the canvas.

        Each frame dict may contain:
          name        str   — frame name
          width       int   — pixels
          height      int   — pixels
          x           int   — canvas x position
          y           int   — canvas y position
          bg_color    str   — hex color, e.g. "#F9F9FB"
          elements    list  — child element dicts (see _element_js)
          corner_radius int — optional, default 0
        """
        frame_snippets = [FigmaClient._frame_js(f) for f in frames]
        all_frames = "\n\n".join(frame_snippets)

        return f"""\
// ─────────────────────────────────────────────────────────────────────────────
// AUTO-GENERATED by Design Lead Agent — paste inside Figma Plugin Runner
// Plugins > Development > Open console  →  paste & press ⌘Enter / Ctrl+Enter
// ─────────────────────────────────────────────────────────────────────────────

function hexToRgb(hex) {{
  const r = parseInt(hex.slice(1, 3), 16) / 255;
  const g = parseInt(hex.slice(3, 5), 16) / 255;
  const b = parseInt(hex.slice(5, 7), 16) / 255;
  return {{ r, g, b }};
}}

function addText(parent, opts) {{
  const t = figma.createText();
  parent.appendChild(t);
  figma.loadFontAsync({{ family: opts.fontFamily || "Inter", style: opts.fontStyle || "Regular" }})
    .then(() => {{
      t.characters = opts.text;
      t.fontSize = opts.fontSize || 16;
      t.fontName = {{ family: opts.fontFamily || "Inter", style: opts.fontStyle || "Regular" }};
      if (opts.color) t.fills = [{{ type: "SOLID", color: hexToRgb(opts.color) }}];
    }});
  t.x = opts.x || 0;
  t.y = opts.y || 0;
  if (opts.width) t.resize(opts.width, t.height);
  t.name = opts.name || "Text";
  return t;
}}

function addRect(parent, opts) {{
  const r = figma.createRectangle();
  parent.appendChild(r);
  r.resize(opts.width || 100, opts.height || 40);
  r.x = opts.x || 0;
  r.y = opts.y || 0;
  r.cornerRadius = opts.cornerRadius || 0;
  if (opts.color) r.fills = [{{ type: "SOLID", color: hexToRgb(opts.color) }}];
  else r.fills = [];
  r.name = opts.name || "Rect";
  if (opts.strokeColor) {{
    r.strokes = [{{ type: "SOLID", color: hexToRgb(opts.strokeColor) }}];
    r.strokeWeight = opts.strokeWeight || 1;
  }}
  return r;
}}

{all_frames}

figma.closePlugin("✅ Frames created by Design Lead Agent");
"""

    @staticmethod
    def _frame_js(frame: dict) -> str:
        name = frame.get("name", "Frame")
        width = frame.get("width", 390)
        height = frame.get("height", 844)
        x = frame.get("x", 0)
        y = frame.get("y", 0)
        bg = frame.get("bg_color", "#FFFFFF")
        corner_radius = frame.get("corner_radius", 0)
        elements = frame.get("elements", [])

        element_js = "\n".join(
            f"  {FigmaClient._element_js(el)}" for el in elements
        )

        return f"""\
// ── Frame: {name} ──
(function() {{
  const frame = figma.createFrame();
  frame.name = {json.dumps(name)};
  frame.resize({width}, {height});
  frame.x = {x};
  frame.y = {y};
  frame.cornerRadius = {corner_radius};
  frame.fills = [{{ type: "SOLID", color: hexToRgb({json.dumps(bg)}) }}];
  figma.currentPage.appendChild(frame);
{element_js}
}})();"""

    @staticmethod
    def _element_js(el: dict) -> str:
        kind = el.get("type", "rect")
        if kind == "text":
            opts = {
                "text": el.get("text", ""),
                "x": el.get("x", 0),
                "y": el.get("y", 0),
                "fontSize": el.get("font_size", 16),
                "fontStyle": el.get("font_style", "Regular"),
                "color": el.get("color", "#1C2024"),
                "name": el.get("name", "Text"),
            }
            if "width" in el:
                opts["width"] = el["width"]
            return f"addText(frame, {json.dumps(opts)});"
        else:
            opts = {
                "width": el.get("width", 100),
                "height": el.get("height", 40),
                "x": el.get("x", 0),
                "y": el.get("y", 0),
                "cornerRadius": el.get("corner_radius", 0),
                "color": el.get("color", "#E8E8FF"),
                "name": el.get("name", "Rect"),
            }
            if "stroke_color" in el:
                opts["strokeColor"] = el["stroke_color"]
                opts["strokeWeight"] = el.get("stroke_weight", 1)
            return f"addRect(frame, {json.dumps(opts)});"
